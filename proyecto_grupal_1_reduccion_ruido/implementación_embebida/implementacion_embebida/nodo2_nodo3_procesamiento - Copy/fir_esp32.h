// FIR pasa-bajas de 129 taps, Hamming, fs=8192 Hz, corte=1350 Hz.
// Retardo de grupo lineal: 64 muestras = 7.8125 ms.
class FIRLowPass129 {
public:
  static const size_t TAPS = 129;
  FIRLowPass129() : writeIndex_(0) { reset(); }
  void reset() {
    for (size_t i = 0; i < TAPS; ++i) delay_[i] = 0.0f;
    writeIndex_ = 0;
  }
  float process(float sample) {
    delay_[writeIndex_] = sample;
    float accumulator = 0.0f;
    int index = (int)writeIndex_;
    for (size_t k = 0; k < TAPS; ++k) {
      accumulator += COEFFICIENTS[k] * delay_[index];
      --index;
      if (index < 0) index = (int)TAPS - 1;
    }
    ++writeIndex_;
    if (writeIndex_ == TAPS) writeIndex_ = 0;
    return accumulator;
  }
private:
  static const float COEFFICIENTS[TAPS];
  float delay_[TAPS];
  size_t writeIndex_;
};

